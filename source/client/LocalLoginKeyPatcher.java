import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.security.KeyFactory;
import java.security.MessageDigest;
import java.security.interfaces.RSAPublicKey;
import java.security.spec.X509EncodedKeySpec;
import java.util.Base64;
import java.util.HexFormat;
import java.util.jar.JarEntry;
import java.util.jar.JarFile;
import java.util.jar.JarOutputStream;
import org.objectweb.asm.ClassReader;
import org.objectweb.asm.ClassVisitor;
import org.objectweb.asm.ClassWriter;
import org.objectweb.asm.MethodVisitor;
import org.objectweb.asm.Opcodes;

/** Builds a local-only runtime copy of the pinned Microbot gamepack. */
public final class LocalLoginKeyPatcher {
    private static final String GAMEPACK_SHA256 =
        "6a9dc96d6b0870f1cc95b47f18be554685245d4606347925cb47d900e49c6255";
    private static final String KEY_CLASS = "ar.class";

    public static void main(String[] args) throws Exception {
        if (args.length != 3 && !(args.length == 4 && args[3].equals("--local-worlds"))) {
            throw new IllegalArgumentException("Usage: LocalLoginKeyPatcher <original-jar> <local-public.pem> <output-jar> [--local-worlds]");
        }

        boolean routeWorlds = args.length == 4;
        Path source = Path.of(args[0]).toRealPath();
        Path output = Path.of(args[2]).toAbsolutePath().normalize();
        if (Files.exists(output) && Files.isSameFile(source, output)) {
            throw new IOException("Use a separate output JAR for the localhost profile");
        }
        if (!MessageDigest.isEqual(MessageDigest.getInstance("SHA-256").digest(Files.readAllBytes(source)),
            HexFormat.of().parseHex(GAMEPACK_SHA256))) {
            throw new IOException("Unexpected injected-client build. This launcher requires the pinned 1.13.6 gamepack.");
        }

        RSAPublicKey key = readPublicKey(Path.of(args[1]));
        if (!key.getPublicExponent().equals(java.math.BigInteger.valueOf(65537))
            || key.getModulus().bitLength() != 2048) {
            throw new IOException("Use the 2048-bit RSA public key generated by the local server kit");
        }

        Path temporary = Files.createTempFile(output.getParent(), ".local-gamepack-", ".jar");
        try {
            try (var original = new JarFile(source.toFile());
                 var updated = new JarOutputStream(Files.newOutputStream(temporary))) {
                if (original.getJarEntry(KEY_CLASS) == null) throw new IOException("Game login key class is missing");
                var entries = original.entries();
                while (entries.hasMoreElements()) {
                    JarEntry entry = entries.nextElement();
                    updated.putNextEntry(new JarEntry(entry.getName()));
                    try (InputStream content = original.getInputStream(entry)) {
                        if (KEY_CLASS.equals(entry.getName())) {
                            updated.write(replaceModulus(content.readAllBytes(), key.getModulus().toString(16)));
                        } else if (SceneTraceInstrumentation.targets(entry.getName())
                            || (routeWorlds && (LocalWorldPortInstrumentation.targets(entry.getName())
                                || entry.getName().equals("az.class") || entry.getName().equals("ic.class")))) {
                            byte[] bytes = content.readAllBytes();
                            if (SceneTraceInstrumentation.targets(entry.getName())) {
                                bytes = SceneTraceInstrumentation.add(entry.getName(), bytes);
                            }
                            if (routeWorlds && LocalWorldPortInstrumentation.targets(entry.getName())) {
                                bytes = LocalWorldPortInstrumentation.route(bytes);
                            }
                            if (routeWorlds && entry.getName().equals("az.class")) {
                                bytes = LocalDisplayInstrumentation.add(bytes);
                            }
                            if (routeWorlds && entry.getName().equals("ic.class")) {
                                bytes = LocalDisplayInstrumentation.addScriptEntry(bytes);
                            }
                            updated.write(bytes);
                        } else {
                            content.transferTo(updated);
                        }
                    }
                    updated.closeEntry();
                }
                copyHelper(updated, "LocalSceneTrace.class");
                if (routeWorlds) copyHelper(updated, "LocalDisplaySettings.class");
            }
            Files.move(temporary, output, StandardCopyOption.REPLACE_EXISTING);
        } finally {
            Files.deleteIfExists(temporary);
        }
        System.out.println("KSP_LOCAL_LOGIN_KEY_READY revision=242 gamepack=1.13.6");
    }

    private static void copyHelper(JarOutputStream output, String name) throws IOException {
        output.putNextEntry(new JarEntry(name));
        try (InputStream content = LocalLoginKeyPatcher.class.getResourceAsStream("/" + name)) {
            if (content == null) throw new IOException("Local gamepack helper missing: " + name);
            content.transferTo(output);
        }
        output.closeEntry();
    }

    private static RSAPublicKey readPublicKey(Path path) throws Exception {
        String pem = Files.readString(path).strip();
        String begin = "-----BEGIN PUBLIC KEY-----";
        String end = "-----END PUBLIC KEY-----";
        if (!pem.startsWith(begin) || !pem.endsWith(end)) {
            throw new IOException("Select local-public.pem from the server kit");
        }
        String body = pem.substring(begin.length(), pem.length() - end.length()).strip();
        byte[] der = Base64.getMimeDecoder().decode(body);
        return (RSAPublicKey) KeyFactory.getInstance("RSA").generatePublic(new X509EncodedKeySpec(der));
    }

    private static byte[] replaceModulus(byte[] original, String modulus) throws IOException {
        ClassReader reader = new ClassReader(original);
        ClassWriter writer = new ClassWriter(reader, 0);
        class KeyVisitor extends ClassVisitor {
            int replacements;

            KeyVisitor() {
                super(Opcodes.ASM9, writer);
            }

            @Override
            public MethodVisitor visitMethod(int access, String name, String descriptor, String signature,
                String[] exceptions) {
                MethodVisitor method = super.visitMethod(access, name, descriptor, signature, exceptions);
                if (!"<clinit>".equals(name)) return method;
                return new MethodVisitor(Opcodes.ASM9, method) {
                    @Override
                    public void visitLdcInsn(Object value) {
                        if (value instanceof String text && text.matches("[0-9a-f]{256}")) {
                            replacements++;
                            super.visitLdcInsn(modulus);
                        } else {
                            super.visitLdcInsn(value);
                        }
                    }
                };
            }
        }
        var visitor = new KeyVisitor();
        reader.accept(visitor, 0);
        if (visitor.replacements != 1) throw new IOException("The pinned game login key layout did not match");
        return writer.toByteArray();
    }
}
